def area_function(vowel: str, n_sections: int = 24):
    """모음별 근사 단면적 함수 (성문 -> 입술 순서, cm^2).

    Story/Titze 의 MRI 면적함수를 파라메트릭하게 단순화한 것이다.
    실제 연구용으로는 측정 면적함수를 쓰는 것이 좋다.
    """
    import torch
    x = torch.linspace(0, 1, n_sections)
    if vowel == "a":       # 인두 좁힘, 구강 개방
        a = 0.3 + 4.0 * torch.sigmoid((x - 0.45) * 14)
    elif vowel == "i":     # 인두 개방, 경구개 좁힘
        a = 4.0 - 3.6 * torch.sigmoid((x - 0.45) * 14)
    elif vowel == "u":     # 연구개 좁힘 + 원순
        a = (0.5 + 3.5 * torch.sigmoid((x - 0.3) * 14))
        a = a * torch.where(x > 0.85, torch.tensor(0.1), torch.tensor(1.0))
    else:                  # 슈와(균일관)
        a = torch.ones(n_sections)
    return a


