"""손으로 적은 음소별 제어 파라미터(학습 없이 합성/검증용).

포먼트 값은 Peterson & Barney(1952) 및 Klatt(1980) 합성기의 관례적 수치를 따랐다.
"""
from __future__ import annotations

# (F1, F2, F3, F4, F5) Hz — 성인 남성 기준
VOWELS = {
    "a":  (730, 1090, 2440, 3400, 4500),   # 아
    "eo": (600, 1000, 2500, 3400, 4500),   # 어
    "o":  (500,  880, 2540, 3400, 4500),   # 오
    "u":  (300,  870, 2240, 3400, 4500),   # 우
    "eu": (400, 1400, 2200, 3400, 4500),   # 으
    "i":  (270, 2290, 3010, 3700, 4500),   # 이
    "e":  (530, 1840, 2480, 3400, 4500),   # 에
}

# 마찰음: (노이즈 중심 Hz, 대역폭 Hz, 협착 위치(0=성문,1=입술), 세기)
FRICATIVES = {
    "s":  (6500, 3000, 0.92, 1.0),    # ㅅ — 앞공동이 짧아 매우 고역
    "sh": (3200, 2000, 0.80, 1.0),    # ㅅ+ㅣ (구개음화)
    "h":  (1200, 2500, 0.05, 0.5),    # ㅎ — 성문 마찰, 성도 전체를 통과
    "f":  (7000, 5000, 0.98, 0.5),
}

BANDWIDTHS = (60, 90, 120, 160, 200)


def area_function(vowel: str, n_sections: int = 24):
    """모음별 근사 단면적 함수 (성문 -> 입술 순서, cm^2).

    Story/Titze 의 MRI 면적함수를 파라메트릭하게 단순화한 것이다.
    실제 연구용으로는 측정 면적함수를 쓰는 것이 좋다.
    """
    import torch
    x = torch.linspace(0, 1, n_sections)
    if vowel == "a":       # 인두 좁힘, 구강 개방
        a = 0.3 + 4.0 * torch.sigmoid((x - 0.45) * 14)
    elif vowel == "i":     # 인두 개방, 경구개 좁힘
        a = 4.0 - 3.6 * torch.sigmoid((x - 0.45) * 14)
    elif vowel == "u":     # 연구개 좁힘 + 원순
        a = (0.5 + 3.5 * torch.sigmoid((x - 0.3) * 14))
        a = a * torch.where(x > 0.85, torch.tensor(0.1), torch.tensor(1.0))
    else:                  # 슈와(균일관)
        a = torch.ones(n_sections)
    return a
